#!/usr/bin/env node
// Deploy the Bittings staff app to its OWN Cloudflare Pages project (bittings-app → https://bittings.app),
// with the app at the site root (/, /signin). Run publish-staff.mjs first: this ships the same published
// copy (website/site/staff/) that turbokeysmith.com/staff/ serves, so both addresses stay identical.
//   node website/_tools/publish-staff.mjs && node website/_tools/deploy-app.mjs
//   add --dry-run to build the folder and print the deploy command without deploying
// (The public-site deploy guard — Google Analytics check — does not apply: the staff app carries no GA.)
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..');
const src = path.join(repo, 'website', 'site', 'staff');
const out = path.join(repo, '.build', 'bittings-app');
const dryRun = process.argv.includes('--dry-run');

if (!fs.existsSync(path.join(src, 'index.html')) || !fs.existsSync(path.join(src, 'version.json'))) {
  console.error('Deploy ABORTED — website/site/staff/ is missing. Run: node website/_tools/publish-staff.mjs');
  process.exit(1);
}
fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(src, out, { recursive: true });

// Same caching rules the app has under turbokeysmith.com/staff/ (see website/site/_headers).
fs.writeFileSync(path.join(out, '_headers'), `# Bittings staff app — https://bittings.app (generated by website/_tools/deploy-app.mjs)
/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: SAMEORIGIN
  Referrer-Policy: strict-origin-when-cross-origin
  X-Robots-Tag: noindex, nofollow
  Permissions-Policy: geolocation=(self), microphone=(), camera=(self)
  Cache-Control: no-cache
  CDN-Cache-Control: no-store
  Cloudflare-CDN-Cache-Control: no-store

# The two pages are never stored by the browser (a phone must not keep an old copy of the app).
/
  ! Cache-Control
  Cache-Control: no-store
/signin
  ! Cache-Control
  Cache-Control: no-store

# Vendor libraries have versioned file names — the browser may keep them a week.
/app/vendor/*
  ! Cache-Control
  Cache-Control: public, max-age=604800
`);

const v = JSON.parse(fs.readFileSync(path.join(out, 'version.json'), 'utf8')).v;
const cmd = 'npx wrangler pages deploy .build/bittings-app --project-name=bittings-app --branch=main --commit-dirty=true';
console.log(`app version ${v} → project bittings-app`);
if (dryRun) { console.log(`[dry run] would now run: ${cmd}`); process.exit(0); }
process.exit(spawnSync(cmd, { cwd: repo, stdio: 'inherit', shell: true }).status ?? 1);
