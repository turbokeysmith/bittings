#!/usr/bin/env node
// Deploy the Bittings MARKETING site to its own Cloudflare Pages project (getbittings → https://getbittings.com).
// The app itself is a different project (bittings-app → https://bittings.app, see deploy-app.mjs).
// Source: bittings-unified/site/ (index.html, legal.html, assets/). Icons are taken from the app folder.
//   node website/_tools/deploy-getbittings.mjs            add --dry-run to build the folder without deploying
// First time only: npx wrangler pages project create getbittings --production-branch=main
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..');
const src = path.join(repo, 'bittings-unified', 'site');
const app = path.join(repo, 'bittings-unified');
const out = path.join(repo, '.build', 'getbittings');
const dryRun = process.argv.includes('--dry-run');

if (!fs.existsSync(path.join(src, 'index.html')) || !fs.existsSync(path.join(src, 'legal.html'))) {
  console.error('Deploy ABORTED — bittings-unified/site/ is missing index.html or legal.html.'); process.exit(1);
}
fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(src, out, { recursive: true });
for (const f of ['favicon.ico', 'apple-touch-icon.png', 'icon-192.png', 'icon-512.png']) fs.copyFileSync(path.join(app, f), path.join(out, f));

// Guard: the marketing site must never ship app code or point its Log in anywhere but the app's own address.
const html = fs.readFileSync(path.join(out, 'index.html'), 'utf8') + fs.readFileSync(path.join(out, 'legal.html'), 'utf8');
if (/href="signin\.html"|app\/assets\/site\//.test(html) || !/https:\/\/bittings\.app\/signin/.test(html)) {
  console.error('Deploy ABORTED — a link still points inside the app folder (Log in must be https://bittings.app/signin).'); process.exit(1);
}

fs.writeFileSync(path.join(out, '_headers'), `# Bittings marketing site — https://getbittings.com (generated by website/_tools/deploy-getbittings.mjs)
/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: geolocation=(), microphone=(), camera=()
  Cache-Control: no-cache

/assets/*
  ! Cache-Control
  Cache-Control: public, max-age=86400
`);
// Old addresses people may have been given while the page lived inside the app.
fs.writeFileSync(path.join(out, '_redirects'), `/welcome / 301
/welcome.html / 301
/signin https://bittings.app/signin 302
/login https://bittings.app/signin 302
/terms /legal#terms 302
/privacy /legal#privacy 302
`);

const cmd = 'npx wrangler pages deploy .build/getbittings --project-name=getbittings --branch=main --commit-dirty=true';
console.log(`marketing site → project getbittings (${fs.readdirSync(out).length} items)`);
if (dryRun) { console.log(`[dry run] would now run: ${cmd}`); process.exit(0); }
process.exit(spawnSync(cmd, { cwd: repo, stdio: 'inherit', shell: true }).status ?? 1);
